/**
 * Projects the canonical catalog (.xjergx/skills, .xjergx/agents, bundled roles and skills)
 * into the native layout of each coding agent, so all of them see the same skills, agents
 * and instructions. Files it writes are recorded in a manifest: they are updated and removed
 * by later syncs, and files you wrote yourself are never overwritten.
 */

export const TARGETS = ['claude', 'codex', 'opencode', 'pi', 'omp'];

export const GENERATED = '<!-- Generated by `xjergx sync` from .xjergx/. Edit the source there, not this file. -->';
const LEGACY_GENERATED = '<!-- Generated by `xjergx install`.';
const MARK_START = '<!-- xjergx:start -->';
const MARK_END = '<!-- xjergx:end -->';

/* ------------------------------------------------------------------ texts */

export function protocolText() {
  return `## xjergx: shared work, memory and skills across coding agents

This project uses the **xjergx** harness. The same backlog, memory, skills and agents are shared by Claude Code,
Codex, OpenCode, Pi and omp, so the user can start something in one tool and continue it in another.

**At the start of every session** run \`xjergx resume\` and read it: it says what the previous agent did, what is
next, the active ticket and the project memory. Continue from there; do not redo finished work.

**While working**
- Before an important decision, search the memory: \`xjergx memory search "<terms>"\` (\`xjergx memory show <id>\` to read one).
  When Engram is installed this is the same store as the Engram MCP tools (\`mem_search\`, \`mem_save\`), so use
  either; without Engram the memory lives in \`.xjergx/memory/\`.
- If the codegraph MCP tools are available (\`codegraph_explore\`, \`codegraph_context\`), use them to find code
  and measure the impact of a change before reading files one by one.
- When you learn something future sessions must know (a decision and its why, a convention, a gotcha, a reusable
  asset, a user preference), record it: \`xjergx memory add "<title>" --body "..." --type decision|convention|gotcha|asset|preference\`
  (\`--global\` for things that apply to all of the user's projects).

**Before the session ends, or when the user says they will continue in another tool**, write a handoff:
\`xjergx handoff --agent <claude|codex|opencode|pi|omp> --summary "what was done and where it stands" --next "next step" --open "question for the user"\`
(\`--next\` and \`--open\` can be repeated).

**Tickets** are routed by size and uncertainty: **ODD** (organic: small/exploratory), **RDD** (requirement-driven:
medium, clear requirements) or **SDD** (spec-driven: large/risky). The \`xjergx\` CLI owns that state. To work on them:
1. Run \`xjergx next --json\` (\`--task <ID>\` for a specific ticket, \`--mode yolo|dry-run\` if the user asked for it).
2. \`run_phase\` → read \`promptFile\` and do exactly what it says (or hand it to the subagent named in \`agent\`).
   If \`conversational\` is true you may ask the user questions. When the phase output exists, go back to 1.
3. \`approve\` → show the user the \`artifact\`; yes → \`xjergx approve\`, no → \`xjergx reject --note "<feedback>"\`. Then 1.
4. \`done\`, \`idle\`, \`stop\` or \`blocked\` → tell the user and stop.
Never edit \`.xjergx/backlog.json\` yourself and never skip a phase. New ticket: \`xjergx add "<description>"\`.

**Skills and agents** are defined once in \`.xjergx/skills/\` and \`.xjergx/agents/\`. To add or change one, edit it
there and run \`xjergx sync\`; the copies in \`.claude/\`, \`.agents/\`, \`.codex/\`, \`.opencode/\` and \`.pi/\` are generated.
`;
}

function roleStub(name, description) {
  return `You are \`${name}\`, a phase agent of the xjergx harness (${description}).

You will be given the path of a prompt file under \`.xjergx/prompts/\`. Read it completely and follow it exactly:
it contains your full role, the task, the artifacts to read and the exact path of the output you must write.
Do not edit \`.xjergx/backlog.json\` and do not run other phases.`;
}

function agentBody(agent) {
  return agent.role ? roleStub(agent.name, agent.description) : agent.body;
}

function agentDescription(agent) {
  return agent.role ? `${agent.description}. Phase agent of the xjergx harness; give it the prompt file path.` : agent.description;
}

/* ------------------------------------------------------------------ per-target plans */

const md = (meta, body) => stringifyFrontmatter(meta, `${GENERATED}\n\n${body}`);

function claudeAgents(agents, base) {
  return agents.map((a) => ({
    path: `${base}/${a.name}.md`,
    content: md({ name: a.name, description: agentDescription(a) }, agentBody(a)),
  }));
}

function skillItems(skills, base) {
  return skills.map((s) => ({ path: `${base}/${s.name}/`, from: s.dir }));
}

function codexAgents(agents, base) {
  return agents.map((a) => ({
    path: `${base}/${a.name}.toml`,
    content: `# Generated by \`xjergx sync\` from .xjergx/. Edit the source there, not this file.\nname = ${tomlString(a.name)}\ndescription = ${tomlString(agentDescription(a))}\ndeveloper_instructions = ${tomlMultiline(agentBody(a))}\n`,
  }));
}

function opencodeAgents(agents, base) {
  return agents.map((a) => ({
    path: `${base}/${a.name}.md`,
    content: md({ description: agentDescription(a), mode: 'subagent' }, agentBody(a)),
  }));
}

/** Pi has no subagents: your own agents become prompt templates (/name). Role stubs are not useful there. */
function piPrompts(agents, base) {
  return agents.filter((a) => !a.role).map((a) => ({
    path: `${base}/${a.name}.md`,
    content: md({ description: a.description }, `${a.body}\n\n$ARGUMENTS`),
  }));
}

function slashCommand(path, argsHint) {
  return {
    path,
    content: md({ description: 'Resume shared work and run the xjergx backlog (ODD / RDD / SDD harness)' },
      `${protocolText()}\nStart now: run \`xjergx resume\`, then continue the work it describes.\n\nUser input (ticket id, mode or a new ticket description): ${argsHint}`),
  };
}

const hookCommands = (agent) => ({
  SessionStart: `command -v xjergx >/dev/null 2>&1 && xjergx resume --agent ${agent} || true`,
  Stop: `command -v xjergx >/dev/null 2>&1 && xjergx handoff --auto --agent ${agent} >/dev/null 2>&1 || true`,
});

/**
 * @returns {{ items: Array<{path: string, content?: string, from?: string}>, blocks: Array<{path: string, section: string}>, hooks: Array<{path: string, agent: string}>, notes: string[] }}
 */
function planProject(target, { skills, agents }) {
  const shared = { path: 'AGENTS.md', section: protocolText() };
  switch (target) {
    case 'claude':
      return {
        items: [...skillItems(skills, '.claude/skills'), ...claudeAgents(agents, '.claude/agents'), slashCommand('.claude/commands/xjergx.md', '$ARGUMENTS')],
        blocks: [{ path: 'CLAUDE.md', section: '@.xjergx/protocol.md' }],
        hooks: [{ path: '.claude/settings.json', agent: 'claude' }],
        notes: [],
      };
    case 'codex':
      return {
        items: [...skillItems(skills, '.agents/skills'), ...codexAgents(agents, '.codex/agents')],
        blocks: [shared],
        hooks: [{ path: '.codex/hooks.json', agent: 'codex' }],
        notes: ['Codex: los hooks (resume automático) requieren `[features] codex_hooks = true` en .codex/config.toml y que el proyecto sea trusted. Sin eso, AGENTS.md le indica a Codex correr `xjergx resume`.'],
      };
    case 'opencode':
      return {
        items: [...skillItems(skills, '.agents/skills'), ...opencodeAgents(agents, '.opencode/agents'), slashCommand('.opencode/commands/xjergx.md', '$ARGUMENTS')],
        blocks: [shared],
        hooks: [],
        notes: [],
      };
    case 'pi':
      return {
        items: [...skillItems(skills, '.agents/skills'), ...piPrompts(agents, '.pi/prompts'), slashCommand('.pi/prompts/xjergx.md', '$ARGUMENTS')],
        blocks: [shared],
        hooks: [],
        notes: [],
      };
    case 'omp':
      // omp inherits the .claude/ layout (skills, agents) and reads AGENTS.md.
      return {
        items: [...skillItems(skills, '.claude/skills'), ...claudeAgents(agents, '.claude/agents')],
        blocks: [shared],
        hooks: [],
        notes: [],
      };
    default:
      throw new Error(`Destino desconocido "${target}". Opciones: ${TARGETS.join(', ')}.`);
  }
}

function planGlobal(target, { skills, agents }) {
  const own = agents; // global agents are always your own (no role stubs)
  switch (target) {
    case 'claude':
    case 'omp':
      return { items: [...skillItems(skills, '.claude/skills'), ...claudeAgents(own, '.claude/agents')], blocks: [], hooks: [], notes: [] };
    case 'codex':
      return { items: [...skillItems(skills, '.agents/skills'), ...codexAgents(own, '.codex/agents')], blocks: [], hooks: [], notes: [] };
    case 'opencode':
      return { items: [...skillItems(skills, '.agents/skills'), ...opencodeAgents(own, '.config/opencode/agents')], blocks: [], hooks: [], notes: [] };
    case 'pi':
      return { items: [...skillItems(skills, '.agents/skills'), ...piPrompts(own, '.pi/agent/prompts')], blocks: [], hooks: [], notes: [] };
    default:
      throw new Error(`Destino desconocido "${target}". Opciones: ${TARGETS.join(', ')}.`);
  }
}

/* ------------------------------------------------------------------ writers */

export function upsertSection(existing, section) {
  const block = `${MARK_START}\n${section.trim()}\n${MARK_END}`;
  if (!existing) return `${block}\n`;
  const start = existing.indexOf(MARK_START);
  const end = existing.indexOf(MARK_END);
  if (start !== -1 && end > start) return existing.slice(0, start) + block + existing.slice(end + MARK_END.length);
  return `${existing.replace(/\s*$/, '')}\n\n${block}\n`;
}

/** Add (or refresh) the xjergx SessionStart/Stop hooks in a Claude- or Codex-style hooks JSON file. */
export function mergeHooks(existingText, agent) {
  let data = {};
  if (existingText?.trim()) {
    try {
      data = JSON.parse(existingText);
    } catch {
      return null; // never clobber a file we cannot parse
    }
  }
  data.hooks ??= {};
  for (const [event, command] of Object.entries(hookCommands(agent))) {
    const groups = (data.hooks[event] ?? []).filter(
      (g) => !(g.hooks ?? []).some((h) => typeof h.command === 'string' && h.command.includes('xjergx ') && h.command.includes(`--agent ${agent}`)),
    );
    groups.push({ hooks: [{ type: 'command', command, timeout: 15 }] });
    data.hooks[event] = groups;
  }
  return `${JSON.stringify(data, null, 2)}\n`;
}

function readManifest(file) {
  if (!existsSync(file)) return { version: 1, targets: {} };
  try {
    const m = JSON.parse(readFileSync(file, 'utf8'));
    return { version: 1, targets: m.targets ?? {} };
  } catch {
    return { version: 1, targets: {} };
  }
}

function sameDir(a, b) {
  if (!existsSync(a) || !existsSync(b)) return false;
  const list = (d) => readdirSync(d, { recursive: true }).map(String).filter((f) => statSync(join(d, f)).isFile()).sort();
  const la = list(a);
  const lb = list(b);
  return la.length === lb.length && la.every((f, i) => f === lb[i] && readFileSync(join(a, f)).equals(readFileSync(join(b, f))));
}

function isLegacyGenerated(file) {
  try {
    const text = readFileSync(file, 'utf8');
    return text.includes(LEGACY_GENERATED) || text.includes(GENERATED);
  } catch {
    return false;
  }
}

/**
 * @param {{ root: string, manifestFile: string, targets: string[], plan: (t: string) => any, extraFiles?: Array<{path: string, content: string}> }} opts
 * @returns {{ written: string[], removed: string[], conflicts: string[], notes: string[] }}
 */
function apply({ root, manifestFile, targets, plan, extraFiles = [] }) {
  const manifest = readManifest(manifestFile);
  const ownedByAnyone = new Set(Object.values(manifest.targets).flat());
  const result = { written: [], removed: [], conflicts: [], notes: [] };
  const desired = new Map(); // path → item
  const perTarget = {};
  const blocks = new Map(); // path → sections[]
  const hooks = new Map();

  for (const t of targets) {
    const p = plan(t);
    perTarget[t] = p.items.map((i) => i.path);
    for (const item of p.items) desired.set(item.path, item);
    for (const b of p.blocks) blocks.set(b.path, b.section);
    for (const h of p.hooks) hooks.set(h.path, h.agent);
    result.notes.push(...p.notes);
  }

  for (const item of [...desired.values(), ...extraFiles]) {
    const abs = join(root, item.path);
    const owned = ownedByAnyone.has(item.path) || extraFiles.includes(item);
    if (item.from) {
      if (sameDir(item.from, abs)) continue;
      if (existsSync(abs) && !owned) {
        result.conflicts.push(item.path);
        continue;
      }
      rmSync(abs, { recursive: true, force: true });
      mkdirSync(dirname(abs), { recursive: true });
      cpSync(item.from, abs, { recursive: true });
    } else {
      if (existsSync(abs)) {
        const current = readFileSync(abs, 'utf8');
        if (current === item.content) continue;
        if (!owned && !isLegacyGenerated(abs)) {
          result.conflicts.push(item.path);
          continue;
        }
      }
      mkdirSync(dirname(abs), { recursive: true });
      writeFileSync(abs, item.content);
    }
    result.written.push(item.path);
  }

  for (const [path, section] of blocks) {
    const abs = join(root, path);
    const current = existsSync(abs) ? readFileSync(abs, 'utf8') : '';
    const next = upsertSection(current, section);
    if (next !== current) {
      writeFileSync(abs, next);
      result.written.push(path);
    }
  }

  for (const [path, agent] of hooks) {
    const abs = join(root, path);
    const current = existsSync(abs) ? readFileSync(abs, 'utf8') : '';
    const next = mergeHooks(current, agent);
    if (next === null) {
      result.conflicts.push(`${path} (JSON inválido, no lo toqué)`);
    } else if (next !== current) {
      mkdirSync(dirname(abs), { recursive: true });
      writeFileSync(abs, next);
      result.written.push(path);
    }
  }

  // Remove what we generated before and no longer generate (renamed/deleted skills and agents).
  const stillWanted = new Set(desired.keys());
  const keptByOthers = new Set(Object.entries(manifest.targets).filter(([t]) => !targets.includes(t)).flatMap(([, v]) => v));
  for (const t of targets) {
    for (const path of manifest.targets[t] ?? []) {
      if (stillWanted.has(path) || keptByOthers.has(path)) continue;
      const abs = join(root, path);
      if (existsSync(abs)) {
        rmSync(abs, { recursive: true, force: true });
        result.removed.push(path);
      }
    }
  }

  for (const t of targets) manifest.targets[t] = perTarget[t].filter((p) => !result.conflicts.includes(p));
  mkdirSync(dirname(manifestFile), { recursive: true });
  writeFileSync(manifestFile, `${JSON.stringify(manifest, null, 2)}\n`);
  result.written = [...new Set(result.written)];
  result.notes = [...new Set(result.notes)];
  return result;
}

/** v0.2 `install` wrote OpenCode files to singular folders that OpenCode no longer reads. */
function removeLegacy(root, removed) {
  for (const dir of ['.opencode/agent', '.opencode/command']) {
    const abs = join(root, dir);
    if (!existsSync(abs)) continue;
    for (const f of readdirSync(abs)) {
      const file = join(abs, f);
      if (f.endsWith('.md') && isLegacyGenerated(file)) {
        rmSync(file);
        removed.push(`${dir}/${f}`);
      }
    }
    if (!readdirSync(abs).length) rmSync(abs, { recursive: true });
  }
}

/** Sync a workspace. @param {import('./paths.js').WorkspacePaths} paths */
export function syncProject(paths, targets) {
  for (const t of targets) if (!TARGETS.includes(t)) throw new Error(`Destino desconocido "${t}". Opciones: ${TARGETS.join(', ')}.`);
  const catalog = { skills: collectSkills(paths, { includeGlobal: false }), agents: collectAgents(paths) };
  const protocol = { path: '.xjergx/protocol.md', content: `${GENERATED}\n\n${protocolText()}` };
  const result = apply({
    root: paths.root,
    manifestFile: paths.manifest,
    targets,
    plan: (t) => planProject(t, catalog),
    extraFiles: [protocol],
  });
  removeLegacy(paths.root, result.removed);
  result.skillProblems = catalog.skills.filter((s) => s.problems.length);
  return result;
}

/** Sync ~/.xjergx/{skills,agents} into each tool's user-level folders. */
export function syncGlobal(targets, home = homedir()) {
  for (const t of targets) if (!TARGETS.includes(t)) throw new Error(`Destino desconocido "${t}". Opciones: ${TARGETS.join(', ')}.`);
  const catalog = { skills: collectSkills(null), agents: collectAgents(null) };
  const result = apply({ root: home, manifestFile: globalPaths().manifest, targets, plan: (t) => planGlobal(t, catalog) });
  result.skillProblems = catalog.skills.filter((s) => s.problems.length);
  return result;
}

/* ------------------------------------------------------------------ import */

const IMPORT_SOURCES = {
  project: {
    skills: ['.claude/skills', '.agents/skills', '.opencode/skills', '.opencode/skill', '.pi/skills'],
    agents: ['.claude/agents', '.opencode/agents', '.opencode/agent', '.codex/agents'],
  },
  global: {
    skills: ['.claude/skills', '.agents/skills', '.config/opencode/skills', '.pi/agent/skills', '.codex/skills'],
    agents: ['.claude/agents', '.config/opencode/agents', '.codex/agents'],
  },
};

function readNativeAgent(file) {
  const text = readFileSync(file, 'utf8');
  if (file.endsWith('.toml')) {
    const t = parseTomlStrings(text);
    if (!t.developer_instructions) return null;
    return { name: t.name || basename(file, '.toml'), description: t.description || '', body: t.developer_instructions };
  }
  const { meta, body } = parseFrontmatter(text);
  return { name: meta.name || basename(file, '.md'), description: meta.description || '', body };
}

/**
 * Adopt skills and agents that were created directly in one tool's folder, so every tool gets them.
 * @param {{ root: string, manifestFile: string, skillsDir: string, agentsDir: string, scope: 'project'|'global', force?: boolean }} o
 */
export function importNative({ root, manifestFile, skillsDir, agentsDir, scope, force = false }) {
  const owned = new Set(Object.values(readManifest(manifestFile).targets).flat());
  const roles = new Set(allAgents());
  const result = { skills: [], agents: [], skipped: [] };
  const seenSkills = new Set();
  const seenAgents = new Set();

  for (const rel of IMPORT_SOURCES[scope].skills) {
    const dir = join(root, rel);
    if (!existsSync(dir)) continue;
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const relPath = `${rel}/${entry.name}/`;
      if (!entry.isDirectory() || entry.name.startsWith('.') || owned.has(relPath)) continue;
      if (!existsSync(join(dir, entry.name, 'SKILL.md'))) continue;
      if (seenSkills.has(entry.name)) continue;
      seenSkills.add(entry.name);
      const dest = join(skillsDir, entry.name);
      if (existsSync(dest) && !force) {
        if (!sameDir(join(dir, entry.name), dest)) result.skipped.push(`${relPath} (ya existe en ${relative(root, dest) || dest}; usá --force)`);
        continue;
      }
      rmSync(dest, { recursive: true, force: true });
      mkdirSync(dirname(dest), { recursive: true });
      cpSync(join(dir, entry.name), dest, { recursive: true });
      result.skills.push(`${relPath} → ${entry.name}`);
    }
  }

  for (const rel of IMPORT_SOURCES[scope].agents) {
    const dir = join(root, rel);
    if (!existsSync(dir)) continue;
    for (const f of readdirSync(dir)) {
      if (!/\.(md|toml)$/.test(f)) continue;
      const relPath = `${rel}/${f}`;
      const file = join(dir, f);
      if (owned.has(relPath) || isLegacyGenerated(file) || readFileSync(file, 'utf8').startsWith('# Generated by `xjergx')) continue;
      const agent = readNativeAgent(file);
      if (!agent || roles.has(agent.name) || seenAgents.has(agent.name)) continue;
      seenAgents.add(agent.name);
      const dest = join(agentsDir, `${agent.name}.md`);
      if (existsSync(dest) && !force) {
        result.skipped.push(`${relPath} (ya existe ${agent.name}.md; usá --force)`);
        continue;
      }
      mkdirSync(agentsDir, { recursive: true });
      writeFileSync(dest, stringifyFrontmatter({ name: agent.name, description: agent.description || agent.name }, agent.body));
      result.agents.push(`${relPath} → ${agent.name}`);
    }
  }
  return result;
}
