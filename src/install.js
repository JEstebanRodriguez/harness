import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { allAgents } from './lanes.js';
import { loadRole } from './prompt.js';

/**
 * HOST MODE integration: generates each tool's native files so you can drive the
 * harness from inside the agent (e.g. `/xjergx` in Claude Code or OpenCode).
 * All of them share the same protocol: loop on `xjergx next --json`.
 */

const MARK_START = '<!-- xjergx:start -->';
const MARK_END = '<!-- xjergx:end -->';
const GENERATED = '<!-- Generated by `xjergx install`. Re-run it to update; local edits will be overwritten. -->';

export const INSTALL_TARGETS = ['claude', 'opencode', 'codex', 'pi'];

export function hostProtocol({ subagents }) {
  return `## xjergx harness

This project uses the **xjergx** harness. Each ticket is routed to a lane by size and uncertainty:
**ODD** (organic: small/exploratory), **RDD** (requirement-driven: medium, clear requirements) or
**SDD** (spec-driven: large/risky). The \`xjergx\` CLI owns the state; you execute the phases.

When the user asks you to work on the backlog, a ticket, or "xjergx":

1. Run \`xjergx next --json\` (add \`--task <ID>\` for a specific ticket, \`--mode yolo|dry-run\` if the user asked for it).
2. Act on the \`action\` field:
   - \`run_phase\` → read \`promptFile\` and do exactly what it says.${subagents ? ' Prefer delegating it to the subagent named in `agent`, passing it the `promptFile` path.' : ''}
     If \`conversational\` is true you may ask the user questions during the phase. When the phase output exists, go back to step 1.
   - \`approve\` → show the user the \`artifact\` and ask if they approve it. Yes → \`xjergx approve\`. No → \`xjergx reject --note "<their feedback>"\`. Then step 1.
   - \`done\`, \`idle\` or \`stop\` → tell the user and stop.
   - \`blocked\` → show the \`reason\` to the user and stop.
3. Never edit \`.xjergx/backlog.json\` yourself, never skip a phase, never write the output of a phase you did not run.

New ticket: \`xjergx add "<description>"\` (optional \`--lane odd|rdd|sdd\` to force a lane). Overview: \`xjergx status\`.
`;
}

function subagentStub(name, description) {
  return `You are \`${name}\`, a phase agent of the xjergx harness (${description}).

You will be given the path of a prompt file under \`.xjergx/prompts/\`. Read it completely and follow it exactly:
it contains your full role, the task, the artifacts to read and the exact path of the output you must write.
Do not edit \`.xjergx/backlog.json\` and do not run other phases.
`;
}

function write(root, rel, content, written) {
  const file = join(root, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
  written.push(rel);
}

/** Insert or replace the xjergx section of a shared instructions file (AGENTS.md). */
export function upsertSection(existing, section) {
  const block = `${MARK_START}\n${section.trim()}\n${MARK_END}`;
  if (!existing) return `${block}\n`;
  const start = existing.indexOf(MARK_START);
  const end = existing.indexOf(MARK_END);
  if (start !== -1 && end > start) return existing.slice(0, start) + block + existing.slice(end + MARK_END.length);
  return `${existing.replace(/\s*$/, '')}\n\n${block}\n`;
}

function writeAgentsMd(root, written) {
  const file = join(root, 'AGENTS.md');
  const existing = existsSync(file) ? readFileSync(file, 'utf8') : '';
  write(root, 'AGENTS.md', upsertSection(existing, hostProtocol({ subagents: false })), written);
}

const roles = (paths) => allAgents().map((name) => ({ name, description: loadRole(paths, name).meta.description ?? name }));

const TARGETS = {
  claude(paths, written) {
    for (const { name, description } of roles(paths)) {
      write(paths.root, `.claude/agents/${name}.md`, `---\nname: ${name}\ndescription: ${description}. Phase agent of the xjergx harness; give it the prompt file path.\n---\n${GENERATED}\n\n${subagentStub(name, description)}`, written);
    }
    write(paths.root, '.claude/commands/xjergx.md', `---\ndescription: Work the xjergx backlog (ODD / RDD / SDD harness)\n---\n${GENERATED}\n\n${hostProtocol({ subagents: true })}\nUser input (ticket id, mode or a new ticket description): $ARGUMENTS\n`, written);
  },

  opencode(paths, written) {
    for (const { name, description } of roles(paths)) {
      write(paths.root, `.opencode/agent/${name}.md`, `---\ndescription: ${description}. Phase agent of the xjergx harness; give it the prompt file path.\nmode: subagent\n---\n${GENERATED}\n\n${subagentStub(name, description)}`, written);
    }
    write(paths.root, '.opencode/command/xjergx.md', `---\ndescription: Work the xjergx backlog (ODD / RDD / SDD harness)\n---\n${GENERATED}\n\n${hostProtocol({ subagents: true })}\nUser input: $ARGUMENTS\n`, written);
    writeAgentsMd(paths.root, written);
  },

  codex(paths, written) {
    writeAgentsMd(paths.root, written);
  },

  pi(paths, written) {
    write(paths.root, '.pi/prompts/xjergx.md', `---\ndescription: Work the xjergx backlog (ODD / RDD / SDD harness)\n---\n${GENERATED}\n\n${hostProtocol({ subagents: false })}\nUser input: $ARGUMENTS\n`, written);
    writeAgentsMd(paths.root, written);
  },
};

/** @returns {string[]} files written, relative to the workspace */
export function install(paths, target) {
  const targets = target === 'all' ? INSTALL_TARGETS : [target];
  for (const t of targets) {
    if (!TARGETS[t]) throw new Error(`No sé instalar "${t}". Opciones: ${INSTALL_TARGETS.join(', ')}, all.`);
  }
  const written = [];
  for (const t of targets) TARGETS[t](paths, written);
  return [...new Set(written)];
}
